# Writes ../oscccm_tests.nv from RFC 3610 section 8 and RFC 8392 appendix A.
#
#   curl -sLo rfc3610.txt https://www.rfc-editor.org/rfc/rfc3610.txt
#   curl -sLo rfc8392.txt https://www.rfc-editor.org/rfc/rfc8392.txt
#   python3 -I gen_ccm_vectors.py rfc3610.txt rfc8392.txt
#   novo fmt ../oscccm_tests.nv
#
# The packet vectors of RFC 3610 are cut out of its text.  Those with a nonce of
# 13 bytes and a tag of 8 bytes (L = 2, M = 8) are the parameters of
# AES-CCM-16-64-128: vectors 1 to 12.  The others have a different nonce or tag
# length and are not tested here.  The last test decrypts the encrypted CWT of
# RFC 8392 appendix A.5, which is AES-CCM-16-64-128 under COSE algorithm 10.
import os
import re
import sys

rfc3610 = open(sys.argv[1]).read().split("\n")
rfc8392 = open(sys.argv[2]).read().split("\n")


def packets():
    starts = [i for i, l in enumerate(rfc3610) if "Packet Vector #" in l]
    out = []
    for n, s in enumerate(starts):
        e = starts[n + 1] if n + 1 < len(starts) else s + 40
        block = rfc3610[s:e]
        key = None
        nonce = None
        inp = ""
        outp = ""
        hdr = None
        mode = None
        for l in block:
            t = l.strip()
            if t.startswith("AES Key ="):
                key = t.split("=", 1)[1].replace(" ", "")
            elif t.startswith("Nonce ="):
                nonce = t.split("=", 1)[1].replace(" ", "")
            elif t.startswith("Total packet length") and "Input" in t:
                m = re.search(r"with (\d+) cleartext", t)
                hdr = int(m.group(1))
                mode = "in"
            elif t.startswith("CBC IV in"):
                mode = None
            elif t.startswith("Total packet length") and "Output" in t:
                mode = "out"
            elif mode and re.match(r"^[0-9A-F]{2}( |$)", t):
                data = t.replace(" ", "")
                if mode == "in":
                    inp += data
                else:
                    outp += data
        out.append((n + 1, key, nonce, hdr, inp.lower(), outp.lower()))
    return out


def block(heading):
    start = next(i for i, l in enumerate(rfc8392) if l.startswith(heading) and i > 900)
    i = start + 1
    while not re.match(r"^   [0-9a-f]{20,}", rfc8392[i]):
        i += 1
    out = ""
    while re.match(r"^   [0-9a-f]+\s*$", rfc8392[i]):
        out += rfc8392[i].strip()
        i += 1
    return out


claims = block("A.1.  Example CWT Claims Set")
key128 = block("A.2.1.  128-Bit Symmetric Key")
encrypted = block("A.5.  Example Encrypted CWT")

# The key is the byte string of 16 after the label 0x20 0x50 (-1: bstr(16)).
k = key128[key128.index("2050") + 4: key128.index("2050") + 4 + 32]
# The IV is the byte string of 13 after 0x05 0x4d (5: bstr(13)); the ciphertext is
# the byte string of 88 after 0x58 0x58.
iv_at = encrypted.index("054d") + 4
iv = encrypted[iv_at: iv_at + 26]
ct_at = encrypted.index("5858", iv_at) + 4
ct = encrypted[ct_at:]
assert len(ct) == 88 * 2 and len(iv) == 26 and len(k) == 32
# Enc_structure = ["Encrypt0", h'a1010a', h''] = 83 68 "Encrypt0" 43 a1010a 40
enc_structure = "83" + "68" + "456e63727970743 0".replace(" ", "") + "43a1010a" + "40"
assert encrypted.startswith("d08343a1010a")

vectors = [p for p in packets() if len(p[2]) == 26 and len(p[5]) - len(p[4]) == 16]

