lines.append("    test.assert_eq_str(hex32(var e), sha(\"6162\"))")
lines.append("    test.case(\"an info longer than 191 bytes is cut to it\")")
lines.append("    var prk: Vec[u8; 32] = Vec.new()")
lines.append("    var salt = load(\"\")")
