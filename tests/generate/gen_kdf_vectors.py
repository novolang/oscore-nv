# Writes ../osckdf_tests.nv from RFC 4231 and RFC 5869.
#
#   curl -sLo rfc4231.txt https://www.rfc-editor.org/rfc/rfc4231.txt
#   curl -sLo rfc5869.txt https://www.rfc-editor.org/rfc/rfc5869.txt
#   python3 -I gen_kdf_vectors.py rfc4231.txt rfc5869.txt
#   novo fmt ../osckdf_tests.nv
#
# The HMAC-SHA-256 vectors are cut out of RFC 4231 section 4 (test cases 1, 2,
# 3, 4, 6 and 7; case 5 is a truncated output) and the HKDF-SHA-256 vectors out
# of RFC 5869 appendix A (test cases 1 to 3).  The SHA-256 digests of messages
# of lengths that straddle the padding boundaries are computed here with
# Python's hashlib, an implementation that shares nothing with the package.
import hashlib
import os
import re
import sys

rfc4231 = open(sys.argv[1]).read().split("\n")
rfc5869 = open(sys.argv[2]).read().split("\n")


def hex_lines(lines, start):
    """The hexadecimal that starts on line `start`, after its label, and goes on over
    the lines after it that begin with hexadecimal."""
    first = re.sub(r"^\s*(?:Key|Data|HMAC-SHA-256)\s*=?\s*", "", lines[start])
    m = re.match(r"^([0-9a-f]{2,})(?:\s|$)", first)
    out = m.group(1)
    i = start + 1
    while i < len(lines):
        m = re.match(r"^\s+([0-9a-f]{2,})(?:\s|$)", lines[i])
        if not m:
            break
        out += m.group(1)
        i += 1
    return out


def case4231(n):
    start = next(i for i, l in enumerate(rfc4231) if re.match(r"^4\.%d\.  Test Case" % (n + 1), l))
    end = start + 40
    block = rfc4231[start:end]
    k = next(i for i, l in enumerate(block) if l.strip().startswith("Key"))
    d = next(i for i, l in enumerate(block) if l.strip().startswith("Data"))
    h = next(i for i, l in enumerate(block) if "HMAC-SHA-256" in l)
    return (hex_lines(block, k), hex_lines(block, d), hex_lines(block, h))


def case5869(n):
    start = next(i for i, l in enumerate(rfc5869) if l.startswith("A.%d.  Test Case" % n))
    block = rfc5869[start:start + 40]

    def field(name):
        idx = next(i for i, l in enumerate(block) if re.match(r"^   %s\s*=" % name, l))
        text = block[idx].split("=", 1)[1].strip()
        if text.startswith("(0 octets)"):
            return ""
        out = re.match(r"0x([0-9a-f]*)", text).group(1)
        j = idx + 1
        while j < len(block) and re.match(r"^\s+[0-9a-f]{2,}(\s|$)", block[j]) and not re.match(r"^   \w+\s*=", block[j]):
            part = block[j].strip().split()[0]
            out += part
            j += 1
        return out
    return {k: field(k) for k in ("IKM", "salt", "info", "PRK", "OKM")}


hmac_cases = [case4231(n) for n in (1, 2, 3, 4, 6, 7)]
hkdf_cases = [case5869(n) for n in (1, 2, 3)]

sha_cases = []
for n in (0, 1, 3, 55, 56, 57, 63, 64, 65, 119, 120, 128, 192, 200, 256):
    msg = bytes((i % 251) for i in range(n))
    sha_cases.append((msg.hex(), hashlib.sha256(msg).hexdigest()))

lines = []
lines.append("// osckdf_tests.nv — SHA-256, HMAC-SHA-256 and HKDF-SHA-256.")
lines.append("//")
lines.append("// GENERATED by tests/generate/gen_kdf_vectors.py; edit the generator, not this file.")
lines.append("//")
lines.append("// The HMAC vectors are RFC 4231 section 4, test cases 1, 2, 3, 4, 6 and 7 (test")
lines.append("// case 5 is a truncated MAC), cut out of the RFC's text.  Cases 6 and 7 have a")
lines.append("// key of 131 bytes, which is hashed before use.  The HKDF vectors are RFC 5869")
lines.append("// appendix A, test cases 1 to 3.  They derive 42 or 82 bytes, and this package")
lines.append("// derives the first 32: the first block of the expansion.  The SHA-256 digests")
lines.append("// are of the messages whose byte i is i mod 251, at the lengths where the")
lines.append("// padding changes shape, 55 to 57 and 119 to 120 among them; they were")
lines.append("// computed with Python's hashlib, which shares no code with this package.")
lines.append("")
lines.append("use std.test")
lines.append("use std.bytes")
lines.append("use osckdf")
lines.append("")
lines.append("fn load(s: Str) -> Vec[u8; 256]")
lines.append("    var m: Vec[u8; 256] = Vec.new()")
lines.append("    let raw = bytes.from_hex(s) ?? bytes.zeros(0)")
lines.append("    for i in 0..bytes.len(raw)")
lines.append("        let _p = m.push((bytes.byte_at(raw, i) ?? 0) as u8)")
lines.append("    m")
lines.append("")
lines.append("fn hex32(var d: Vec[u8; 32]) -> Str")
lines.append("    var b = bytes.zeros(d.len())")
lines.append("    for i in 0..d.len()")
lines.append("        bytes.set_u8(b, i, d[i] as Int)")
lines.append("    bytes.to_hex(b)")
lines.append("")
lines.append("fn sha(msg: Str) -> Str")
lines.append("    var m = load(msg)")
lines.append("    var d: Vec[u8; 32] = Vec.new()")
lines.append("    osckdf.sha256(var m, m.len(), var d)")
lines.append("    hex32(var d)")
lines.append("")
lines.append("fn mac(key: Str, data: Str) -> Str")
lines.append("    var k = load(key)")
lines.append("    var m = load(data)")
lines.append("    var d: Vec[u8; 32] = Vec.new()")
lines.append("    osckdf.hmac_sha256(var k, k.len(), var m, m.len(), var d)")
lines.append("    hex32(var d)")
lines.append("")
lines.append("fn hkdf_first(ikm: Str, salt: Str, info: Str) -> Str")
lines.append("    var i = load(ikm)")
lines.append("    var s = load(salt)")
lines.append("    var inf = load(info)")
lines.append("    var prk: Vec[u8; 32] = Vec.new()")
lines.append("    osckdf.hkdf_extract(var s, s.len(), var i, i.len(), var prk)")
lines.append("    var t1: Vec[u8; 32] = Vec.new()")
lines.append("    osckdf.hkdf_expand_first(var prk, var inf, inf.len(), var t1)")
lines.append("    hex32(var prk) + \"/\" + hex32(var t1)")
lines.append("")
lines.append("@test")
lines.append("fn test_sha256_of_the_nist_examples() [io]")
lines.append("    test.case(\"the empty message\")")
lines.append("    test.assert_eq_str(sha(\"\"), \"e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855\")")
lines.append("    test.case(\"abc\")")
lines.append("    test.assert_eq_str(sha(\"616263\"), \"ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad\")")
lines.append("    test.case(\"the 56-byte message of FIPS 180-4, two blocks\")")
lines.append("    test.assert_eq_str(sha(\"6162636462636465636465666465666765666768666768696768696a68696a6b696a6b6c6a6b6c6d6b6c6d6e6c6d6e6f6d6e6f706e6f7071\"),")
lines.append("                       \"248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1\")")
lines.append("")
lines.append("@test")
lines.append("fn test_sha256_at_the_lengths_where_the_padding_changes() [io]")
for msg, dig in sha_cases:
    n = len(msg) // 2
    lines.append("    test.case(\"%d bytes\")" % n)
    lines.append("    test.assert_eq_str(sha(\"%s\"),\n                       \"%s\")" % (msg, dig))
lines.append("")
lines.append("@test")
lines.append("fn test_hmac_sha256_of_rfc_4231() [io]")
for i, (k, d, h) in enumerate(hmac_cases):
    lines.append("    test.case(\"test case %d: a key of %d bytes and %d bytes of data\")" % ([1, 2, 3, 4, 6, 7][i], len(k) // 2, len(d) // 2))
    lines.append("    test.assert_eq_str(mac(\"%s\",\n                          \"%s\"),\n                       \"%s\")" % (k, d, h))
lines.append("")
lines.append("@test")
lines.append("fn test_hkdf_sha256_of_rfc_5869() [io]")
for i, c in enumerate(hkdf_cases):
    lines.append("    test.case(\"appendix A.%d: the PRK, and the first 32 bytes of the OKM\")" % (i + 1))
    lines.append("    test.assert_eq_str(hkdf_first(\"%s\",\n                                 \"%s\",\n                                 \"%s\"),\n                       \"%s/%s\")" % (c["IKM"], c["salt"], c["info"], c["PRK"], c["OKM"][:64]))
lines.append("")
lines.append("@test")
lines.append("fn test_hmac_cuts_what_does_not_fit_and_hashes_what_it_is_given() [io]")
lines.append("    test.case(\"a message past 192 bytes is cut to 192\")")
lines.append("    var k = load(\"0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b\")")
lines.append("    var long = load(\"%s\")" % ("ab" * 255))
lines.append("    var cut = load(\"%s\")" % ("ab" * 192))
lines.append("    var a: Vec[u8; 32] = Vec.new()")
lines.append("    var b: Vec[u8; 32] = Vec.new()")
lines.append("    osckdf.hmac_sha256(var k, 20, var long, 255, var a)")
lines.append("    osckdf.hmac_sha256(var k, 20, var cut, 192, var b)")
lines.append("    test.assert_eq_str(hex32(var a), hex32(var b))")
lines.append("    test.case(\"a length past the buffer is cut to what the buffer holds\")")
lines.append("    var short = load(\"6162\")")
lines.append("    var c: Vec[u8; 32] = Vec.new()")
