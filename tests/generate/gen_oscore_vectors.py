# Writes ../oscore_rfc8613_tests.nv from the text of RFC 8613 appendix C.
#
#   curl -sLo rfc8613.txt https://www.rfc-editor.org/rfc/rfc8613.txt
#   python3 -I gen_oscore_vectors.py rfc8613.txt
#   novo fmt ../oscore_rfc8613_tests.nv
#
# Every hexadecimal string of the file is cut out of the RFC: the inputs and
# outputs of the three key derivations of C.1 to C.3, and the requests and
# responses of C.4 to C.8.
import os
import re
import sys

raw = open(sys.argv[1]).read().split("\n")
lines = [l for l in raw if not re.match(r"^(Selander, et al\.|RFC 8613 )", l) and "\x0c" not in l]
text = "\n".join(lines)


def section(start, end):
    a = text.rindex(start)
    b = text.index(end, a + len(start))
    return text[a:b]


def grab(block, label, occurrence=0):
    """The hexadecimal after `label:` up to `(N byte`, whitespace removed."""
    pat = re.escape(label) + r"\s*:\s*(?:0x)?([0-9a-fA-F \n]*?)\s*\(\s*\d+\s+byte"
    ms = list(re.finditer(pat, block))
    return re.sub(r"\s", "", ms[occurrence].group(1)).lower()


def grab_len(block, label):
    pat = re.escape(label) + r"\s*:\s*(?:0x)?([0-9a-fA-F \n]*?)\s*\(\s*\d+\s+byte"
    return re.search(pat, block) is not None


deriv = {}
names = [("C.1.1", "C.1.2"), ("C.1.2", "C.2.  Test Vector 2"), ("C.2.1", "C.2.2"), ("C.2.2", "C.3.  Test Vector 3"), ("C.3.1", "C.3.2"), ("C.3.2", "C.4.  Test Vector 4")]
for a, b in names:
    blk = section(a + ".  ", b)
    d = {}
    d["secret"] = grab(blk, "Master Secret")
    d["salt"] = grab(blk, "Master Salt") if "Master Salt:" in blk else None
    d["sid"] = grab(blk, "Sender ID")
    d["rid"] = grab(blk, "Recipient ID")
    d["ctx"] = grab(blk, "ID Context") if "ID Context:" in blk.split("From the previous")[0] else None
    d["info_s"] = grab(blk, "info (for Sender Key)")
    d["info_r"] = grab(blk, "info (for Recipient Key)")
    d["info_iv"] = grab(blk, "info (for Common IV)")
    d["skey"] = grab(blk, "Sender Key")
    d["rkey"] = grab(blk, "Recipient Key")
    d["civ"] = grab(blk, "Common IV")
    d["snonce"] = grab(blk, "sender nonce")
    d["rnonce"] = grab(blk, "recipient nonce")
    deriv[a] = d

# The info strings are written "0x8540... (9 bytes)" or split over two lines with the
# byte count on the second: grab handles both.  The key lines are "Sender Key:" in the
# Outputs list, which comes after the info lines, so take the occurrence that is a key.


def key_of(blk, label):
    ms = list(re.finditer(re.escape(label) + r":\s*(?:0x)?([0-9a-fA-F \n]*?)\s*\(\s*16\s+byte", blk))
    return re.sub(r"\s", "", ms[0].group(1)).lower()


for a, b in names:
    blk = section(a + ".  ", b)
    deriv[a]["skey"] = key_of(blk, "Sender Key")
    deriv[a]["rkey"] = key_of(blk, "Recipient Key")

msgs = {}
for n, a, b in (("C.4", "C.4.  Test Vector 4", "C.5.  Test Vector 5"), ("C.5", "C.5.  Test Vector 5", "C.6.  Test Vector 6"),
                ("C.6", "C.6.  Test Vector 6", "C.7.  Test Vector 7"), ("C.7", "C.7.  Test Vector 7", "C.8.  Test Vector 8"),
                ("C.8", "C.8.  Test Vector 8", "Appendix D.  Overview")):
    blk = section(a, b)
    m = {}
    m["plain_msg"] = grab(blk, "Unprotected CoAP request" if n in ("C.4", "C.5", "C.6") else "Unprotected CoAP response")
    m["aad_array"] = grab(blk, "aad_array")
    m["aad"] = grab(blk, "AAD")
    m["plaintext"] = grab(blk, "plaintext")
    m["nonce"] = grab(blk, "nonce")
    m["opt"] = grab(blk, "OSCORE option value") if grab_len(blk, "OSCORE option value") else ""
    m["ct"] = grab(blk, "ciphertext")
    prot = "Protected CoAP request (OSCORE message)" if n in ("C.4", "C.5", "C.6") else "Protected CoAP response (OSCORE message)"
    m["prot"] = grab(blk, prot)
    msgs[n] = m

